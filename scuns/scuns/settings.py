def practice_env_int(name, default, minimum, maximum):
    try:
        value = int(os.environ.get(name, str(default)))
    except ValueError:
        raise ImproperlyConfigured(f'{name} должен быть целым числом.')
    return max(minimum, min(maximum, value))


